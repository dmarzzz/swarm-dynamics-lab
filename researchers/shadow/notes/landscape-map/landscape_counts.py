"""Reproducible corpus counts behind synthesis/landscape.md.

Usage (from the repo root):  python3 researchers/shadow/notes/landscape-map/landscape_counts.py > researchers/shadow/notes/landscape-map/counts.md

Reads only library/*/*.md frontmatter and body text. No network, no model calls.
Concept counts are case-insensitive regex hits anywhere in an entry (summary, notes, links), so an entry that
merely mentions a term counts. They measure what the catalogue talks about, not what the literature contains.
"""
import collections
import itertools
import os
import re
import subprocess
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
LIB = os.path.join(ROOT, "library")

TOPICS = ["collective-motion", "collective-decision", "swarm-robotics", "swarm-intelligence", "active-matter",
          "sync-consensus", "criticality-measurement", "marl-emergence", "llm-agent-swarms", "crowds-and-traffic",
          "sybil-resistance", "fork-merge-security", "swarm-detection", "agent-budgets", "decision-models", "dissent"]
SHORT = {"collective-motion": "motion", "collective-decision": "decis", "swarm-robotics": "robot",
         "swarm-intelligence": "SI", "active-matter": "active", "sync-consensus": "sync",
         "criticality-measurement": "crit", "marl-emergence": "marl", "llm-agent-swarms": "llm",
         "crowds-and-traffic": "crowd", "sybil-resistance": "sybil", "fork-merge-security": "fork",
         "swarm-detection": "detect", "agent-budgets": "budget", "decision-models": "dmodel", "dissent": "dissent"}
NATURAL = {"collective-motion", "collective-decision", "swarm-robotics", "swarm-intelligence", "active-matter",
           "sync-consensus", "criticality-measurement", "marl-emergence", "crowds-and-traffic"}
SECURITY = {"sybil-resistance", "fork-merge-security", "swarm-detection"}

CONCEPTS = [
    ("order parameter", r"order parameter"),
    ("phase transition / criticality / spinodal", r"phase transition|critical point|criticality|spinodal"),
    ("Ising / mean-field / Glauber", r"\bIsing\b|mean[- ]field|Curie-Weiss|Glauber"),
    ("Kuramoto / swarmalator", r"Kuramoto|swarmalator"),
    ("correlation length / scale-free correlations", r"correlation length|scale-free correlation"),
    ("transfer entropy / causation entropy", r"transfer entropy|causation entropy"),
    ("topological vs metric neighbours", r"topological (interaction|neighbo|distance)|metric (interaction|distance)"),
    ("quorum response / threshold", r"quorum (response|threshold|sensing)"),
    ("cross-inhibition / stop signal", r"cross[- ]inhibition|stop signal"),
    ("speed-accuracy trade-off", r"speed[- ]accuracy"),
    ("uninformed individuals", r"uninformed (individuals|agents)"),
    ("committed minority / tipping", r"committed minority|tipping point|tipping fraction"),
    ("DeGroot / Friedkin-Johnsen", r"DeGroot|Friedkin"),
    ("W-MSR / r-robust resilient consensus", r"W-MSR|resilient (asymptotic )?consensus|r-robust"),
    ("Byzantine", r"Byzantine"),
    ("Sybil", r"\bSybil"),
    ("false-name", r"false-name"),
    ("correlated errors / N-version / design diversity", r"correlated error|N-version|design diversity"),
    ("effective sample size / N_eff / design effect", r"N_eff|effective (team|sample) size|design effect"),
    ("wisdom of crowds", r"wisdom of (the )?crowd"),
    ("stigmergy", r"stigmerg"),
    ("homophily vs contagion", r"homophily"),
    ("stop-and-go / jamming", r"stop-and-go|phantom jam|jamming"),
    ("mean-field RL / mean-field game", r"mean[- ]field (multi-agent )?(reinforcement|RL|game)"),
    ("Ringelmann / social loafing", r"Ringelmann|social loafing"),
]


def load():
    rows = []
    for kind in sorted(os.listdir(LIB)):
        d = os.path.join(LIB, kind)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".md"):
                continue
            s = open(os.path.join(d, f), encoding="utf-8").read()
            m = re.match(r"---\n(.*?)\n---", s, re.S)
            if not m:
                continue
            try:
                fm = yaml.safe_load(m.group(1))
            except yaml.YAMLError:
                continue
            if not isinstance(fm, dict):
                continue
            rows.append({"id": fm.get("id"), "type": fm.get("type"), "year": fm.get("year"),
                         "topics": set(fm.get("topics") or []), "rel": fm.get("relevance"),
                         "depth": fm.get("read_depth"), "text": s})
    return rows


def main():
    rows = load()
    try:
        head = subprocess.check_output(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        head = "unknown"
    out = sys.stdout
    out.write(f"# Corpus counts for synthesis/landscape.md\n\nGenerated by `landscape_counts.py` at commit `{head}`. "
              f"{len(rows)} library entries parsed.\n\n")

    out.write("## Entries, relevance-5 entries and read depth per topic\n\n")
    out.write("| topic | entries | relevance 5 | full or ran | share full or ran | from 2025-2026 |\n|---|---|---|---|---|---|\n")
    for t in TOPICS:
        sel = [r for r in rows if t in r["topics"]]
        n = len(sel)
        r5 = sum(1 for r in sel if r["rel"] == 5)
        fr = sum(1 for r in sel if r["depth"] in ("full", "ran"))
        recent = sum(1 for r in sel if str(r["year"]) in ("2025", "2026"))
        out.write(f"| {t} | {n} | {r5} | {fr} | {100 * fr / max(n, 1):.0f}% | {100 * recent / max(n, 1):.0f}% |\n")

    out.write("\n## Co-tag matrix (entries carrying both topics)\n\n")
    pair = collections.Counter()
    for r in rows:
        ts = sorted(t for t in r["topics"] if t in TOPICS)
        for a, b in itertools.combinations(ts, 2):
            pair[(a, b)] += 1
    out.write("| | " + " | ".join(SHORT[t] for t in TOPICS) + " |\n|" + "---|" * (len(TOPICS) + 1) + "\n")
    for a in TOPICS:
        cells = []
        for b in TOPICS:
            cells.append("-" if a == b else str(pair[tuple(sorted((a, b)))]))
        out.write(f"| {SHORT[a]} | " + " | ".join(cells) + " |\n")

    out.write("\n## Concept mentions by community\n\n")
    out.write("Natural/engineered = any of " + ", ".join(sorted(NATURAL)) + ". Security = "
              + ", ".join(sorted(SECURITY)) + ". An entry can count in more than one column.\n\n")
    out.write("| concept | natural/engineered | llm-agent-swarms | security |\n|---|---|---|---|\n")
    for name, pat in CONCEPTS:
        rx = re.compile(pat, re.I)
        nat = llm = sec = 0
        for r in rows:
            if not rx.search(r["text"]):
                continue
            if r["topics"] & NATURAL:
                nat += 1
            if "llm-agent-swarms" in r["topics"]:
                llm += 1
            if r["topics"] & SECURITY:
                sec += 1
        out.write(f"| {name} | {nat} | {llm} | {sec} |\n")


if __name__ == "__main__":
    main()
